// Builds the classic AEM client library from the widget source.
// AEM clientlibs load plain (non-module) scripts, so the ES module is wrapped
// in an IIFE that mounts every .searchblox-search element on the page.
// Usage: node scripts/build-aem.mjs
import { mkdir, readFile, writeFile } from 'node:fs/promises';

const root = new URL('..', import.meta.url);
const src = (p) => new URL(`widgets/searchblox-search/${p}`, root);
const out = (p) => new URL(`aem-classic/clientlib-searchblox/${p}`, root);

const core = (await readFile(src('searchblox-core.js'), 'utf8')).replace(/^export /gm, '');
const css = await readFile(src('searchblox-search.css'), 'utf8');

const bundle = `/* Generated by scripts/build-aem.mjs from widgets/searchblox-search/. Do not edit. */
(function () {
${core}
  const mounted = new WeakSet();
  function init() {
    document.querySelectorAll('.searchblox-search').forEach((el) => {
      if (mounted.has(el)) return;
      mounted.add(el);
      mount(el, { ...(window.SearchBloxConfig || {}), ...el.dataset });
    });
  }
  window.SearchBloxSearch = { mount, init };
  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', init);
  else init();
}());
`;

const config = `// Site-wide settings for every SearchBlox search box on the site.
// A data-* attribute on an element overrides the same setting for that element.
window.SearchBloxConfig = {
  domain: 'https://search.example.com',
  collections: '',
  facets: 'contenttype,keywords:Topics',
  pageSize: 10,
};
`;

await mkdir(out('js'), { recursive: true });
await mkdir(out('css'), { recursive: true });
await writeFile(out('.content.xml'), `<?xml version="1.0" encoding="UTF-8"?>
<jcr:root xmlns:cq="http://www.day.com/jcr/cq/1.0" xmlns:jcr="http://www.jcp.org/jcr/1.0"
    jcr:primaryType="cq:ClientLibraryFolder"
    allowProxy="{Boolean}true"
    categories="[searchblox.search]"/>
`);
await writeFile(out('js.txt'), '#base=js\nsearchblox-config.js\nsearchblox-search.js\n');
await writeFile(out('css.txt'), '#base=css\nsearchblox-search.css\n');
await writeFile(out('js/searchblox-search.js'), bundle);
await writeFile(out('css/searchblox-search.css'), css);
try {
  await readFile(out('js/searchblox-config.js'));
} catch {
  await writeFile(out('js/searchblox-config.js'), config);
}
console.log('Built aem-classic/clientlib-searchblox/');
